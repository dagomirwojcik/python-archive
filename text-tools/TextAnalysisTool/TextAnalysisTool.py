# Defining the class

class analysedText(object):

    # Default constructor

    def __init__ (self, text):
        punctuations = ['.', '!', ',', '?']
        self.fmtText = text.lower()
        for punctuation in punctuations:
            self.fmtText = self.fmtText.replace(punctuation, '')

    # Method to get frequency of all words

    def freqAll(self):    
        words = self.fmtText.split()
        frequencies = {}
        for word in words:
            frequencies[word] = frequencies.get(word, 0) + 1
        return frequencies

    # Method to get frequency of a specific word
            
    def freqOf(self, word):
        return self.fmtText.split().count(word.lower())