# Ask user to input a string
quantity_input = input("Enter a word or sentence -> ")

# Convert the user input to lowercase for consistancy
quantity_input = quantity_input.lower()

# Creating a Sequence Class to recall later
alphabet = list("abcdefghijklmnopqrstuvwxyz")

# Declaring an Empty List for frequencies 
frequencies = []

# Create a loop for each letter of the alphabet
for letter in alphabet:
  # count the number of times the letter appears in the user input
  alpha_count = quantity_input.count(letter)
  # append the count to the frequencies list
  frequencies.append(alpha_count)

# display the frequencies of each letter
for i in range(len(alphabet)):
  print(f"The letter", alphabet[i], "is used", frequencies[i], "time(s)")


