# Defining the list of fruits

wish_fruit = ["Apple", "banana", "Mango"]

# Try block to handle exceptions when the user inputs an index that is out of range or not a number

try:
    index = int(input("Choose a fruit by entering its index -> "))
    selected_fruit = wish_fruit[index]
    print(f"You chose: {selected_fruit}")
except IndexError:
    print("IndexError: The index you entered is not in the list.")
except ValueError:
    print("ValueError: Please enter a valid number.")
finally:
    print("Thank you for choosing a fruit!")