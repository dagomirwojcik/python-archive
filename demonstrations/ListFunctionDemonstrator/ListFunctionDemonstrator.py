# Create a List of Gaming Platforms

def create_list():
	return ["PlayStation", "Xbox", "Steam", "iOS", "Google Play"]

# Get Information About the List

def get_info(my_list):
	return my_list[0], my_list[-2], len(my_list)

# Get a Partial List

def get_partial(my_list):
	return my_list[1:4]

# Get the Last Three Items in Reverse Order

def get_last_three(my_list):
	return my_list[-3:][::-1]

# Double the List

def double_list(my_list):
	return my_list + my_list

# Amend the List by Changing the Second Item to None and Adding "Bye" to the End

def amend(my_list):
	amended_list = my_list.copy()
	amended_list[1] = None
	amended_list.append("Bye")
	return amended_list

