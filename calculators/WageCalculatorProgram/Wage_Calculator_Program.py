num_hours = int(input("Please Enter the Amount of Hours Worked by Employee -> "))
sales = float(input("Please Enter the Amount of Sales for the Employee -> "))

# Setting up the Variables

wages = 0.0
normal_hours = 0
overtime_hours = 0
commission = 0

# Setting Conditions Depending on the Inputs Provided

if num_hours <= 40:
    normal_hours = num_hours
    
if num_hours > 40:
    normal_hours = 40
    overtime_hours = num_hours - 40
    
if sales > 1.00 and sales < 99.99:
    commission = sales * 5 / 100.0
    
if sales > 100.0 and sales < 299.99:
    commission = sales * 10 / 100.00
    
if sales > 300:
    commission = sales * 15 / 100.0
    
# Final Calculation

wages = normal_hours * 9.5 + overtime_hours * (9.5 * 1.5) + commission

