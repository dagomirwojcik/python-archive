import math

# Gather user input for the coefficients of a quadratic equation and store them in variables.

CoefficientA = float(input("\nEnter the coefficient A -> \n"))
CoefficientB = float(input("\nEnter the coefficient B -> \n"))
CoefficientC = float(input("\nEnter the coefficient C -> \n"))

# Display the coefficients of the equation.

print("\nThe coefficients of the equation are:\n")
print("Coefficient A -> ", CoefficientA)
print("Coefficient B -> ", CoefficientB)
print("Coefficient C -> ", CoefficientC)

# Calculate the descriminant of the quadratic equation.

Discriminant = CoefficientB**2 - 4*CoefficientA*CoefficientC

# Calculate the roots of the quadratic equation using the quadratic formula.

if Discriminant < 0:
	print("\nThe equation has no roots.")
else:
	Root1 = (-CoefficientB + math.sqrt(Discriminant)) / (2*CoefficientA)
	Root2 = (-CoefficientB - math.sqrt(Discriminant)) / (2*CoefficientA)

	# Output the results.

	print()
	print("\nThe roots of the equation:\n")
	print("Root #1 -> ", round(Root1,2))
	print("Root #2 -> ", round(Root2,2))