# Input the employee's name and number of hours worked in a week.

employee_name = input("Enter the employee's name -> ")
hours_worked = float(input("Enter the number of hours worked in a week -> "))

# Define the hourly wage and standard workweek hours.

hourly_wage = 22
standard_hours = 40

# Calculate the total pay for regular hours.

if hours_worked <= standard_hours:
    regular_pay = hours_worked * hourly_wage
    overtime_pay = 0

else:
    regular_pay = standard_hours * hourly_wage
    overtime_hours = hours_worked - standard_hours
    overtime_pay = overtime_hours * hourly_wage * 1.5

# Calculate the total pay in a week.

total_pay = regular_pay + overtime_pay

# Print the employee's name, regular pay, overtime pay and the total pay to two significant figures.

print()
print(f"Employee Name: {employee_name}")
print(f"Regular Pay: £{regular_pay:.2f}")
print(f"Overtime Pay: £{overtime_pay:.2f}")
print(f"Total Pay: £{total_pay:.2f}")
