# Function to add two numbers

def add(num1, num2):
    return num1 + num2

# Function to subtract two numbers

def subtract(num1, num2):
    return num1 - num2

# Function to multiply two numbers

def multiply(num1, num2):
    return num1 * num2

# Function to divide two numbers, forbidding division by zero

def divide(num1, num2):
    if num2 == 0:
        return "Cannot divide by zero"
    return num1 / num2

# Function to perform the chosen operation based on user input

def calculator(num1, num2, operator):
    if operator == '+':
        return add(num1, num2)
    elif operator == '-':
        return subtract(num1, num2)
    elif operator == '*':
        return multiply(num1, num2)
    elif operator == '/':
        return divide(num1, num2)
    else:
        return "Invalid operator"

# Function to get user input for two numbers and an operator

def get_user_operator_choice():
    num1 = float(input("Enter the first number -> "))
    num2 = float(input("Enter the second number -> "))
    operator = input("Enter your operator choice (+, -, *, /) -> ")
    return num1, num2, operator

# Main function to run the calculator program

def main():
    num1, num2, operator = get_user_operator_choice()
    result = calculator(num1, num2, operator)
    print(f"Result: {result}")

main()