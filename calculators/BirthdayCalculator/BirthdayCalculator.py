# Import the datetime module.

from datetime import datetime

# Input birthday from the user and store it in a variable.

birthday = input("Enter your birthday (DD-MM-YYYY) -> ")
birthday_date = datetime.strptime(birthday, "%d-%m-%Y")
today = datetime.now()
next_birthday = birthday_date.replace(year=today.year)

# Calculate the number of days until the next birthday and print the result.

if next_birthday < today:
    next_birthday = birthday_date.replace(year=today.year + 1)

elif next_birthday == today:
    print("Happy Birthday! Today is your birthday!")

else:
    days_left = (next_birthday - today).days
    print(f"Days left until your next birthday: {days_left}")

# Calculate the number of days since the last birthday and print the result.

previous_birthday = birthday_date.replace(year=today.year - 1)
days_since_last_birthday = (today - previous_birthday).days
print(f"Days since your last birthday: {days_since_last_birthday}")