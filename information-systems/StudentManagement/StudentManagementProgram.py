# Declare A List
student_list = []

# Main Menu
print("Student Management Program")
print("-" * 26)
print()
print("Main Menu")
print("-" * 9)

# Add Students to the List
def add_info():
    student_name = input("Enter the Student's Name -> ")
    student_list.append(student_name)
    print()
    print(f"Added: {student_name} to the list")
    print()
        
# Menu Function
def menu():
    print("Choose an option:")
    print()
    print("1. Add a Student to the List")
    print("2. List of Students")
    print("3. Sort Student List Alphabetically")
    print("4. Clear the List of Students")
    print("5. Exit the Program")
    print()
    choice = int(input("Enter Your Choice -> "))
    print()
    return choice

while True:
    # Get the User Choice
    choice = menu()

    # Perform the Action Depending on Choice
    if choice == 1:
        add_info()
    elif choice == 2:
        print("Current Students:", student_list)
        print()
    elif choice == 3:
        student_list.sort()
        print("Student List Sorted Alphabetically by First Name")
        print()
    elif choice == 4:
        student_list.clear()
        print("Student List Cleared Successfully")
        print()
    elif choice == 5:
        print("Goodbye.")
        break
    else:
        print("Invalid choice. Try again.")