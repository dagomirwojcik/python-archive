menu_options = ("1", "2", "3", "4")

while True:
    print("Product Database Program")
    print("-" * 24)
    print()
    print("Main Menu")
    print("-" * 9)
    
    print("Choose an option:")
    print()
    print("1. Add a product to the database")
    print("2. List of Products")
    print("3. Remove a product from the database")
    print("4. Exit program")
    print()

    menu_select = input("Enter Menu Option -> ")
    
    if menu_select in menu_options:
        break
    
    else:
        print()
        print("Invalid choice, please try again!")
        print()
        
    # Fucntion to exit the program
    if menu_select == "4":
        break
    
    

# Database Program will display a main menu followed by an input which the user must follow to use the program.
# Function to add information to the dictionary
if menu_select == "1":
   product_name = input("Enter the Product Name -> ")
   product_serial = input("Enter the Product Serial Number -> ")
   product_quantity = input("Enter the Quantity in Stock -> ")
   product_info = [product_name, product_serial, product_quantity]
   product_dict.update(product_info)
   print(f"Added: {{'{product_name}': '{product_serial}': '{product_quantity}'}}")
   print()

# Function to view the information in the dictionary
if menu_select == "2":
    print()
    print("Current Dictionary:", product_dict)
    print()


# Function to delete information from the dictionary
if menu_select == "3":
    product_name = input("Enter the product name you wish to delete -> ")
    if product_name in product_dict:
        del product_dict[product_info, product_serial, product_quantity]
        print(f"Deleted: {product_name}")
        print()
    else:
        print(f"Key '{product_name}' not found.")
        print()