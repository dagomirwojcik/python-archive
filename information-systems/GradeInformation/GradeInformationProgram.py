# Declaring a list & variables.

mark_list = []

total_mark = 0
max_mark = 0
min_mark = 0

# Collect number of students.

students = int(input("Enter the Number of Students -> "))

# Add student scores to the list.

for i in range(int(students)):
    mark = int(input("What Mark was Achieved by this Student? -> "))
    
    mark_list.append(mark)
 
# Declaring the maximum and minimum marks.

mark_list.sort()

max_mark = mark_list[-1]

min_mark = mark_list[0]

# Adding all the array numbers for further calculations.

