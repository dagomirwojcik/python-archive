# Declare the Guest List

guest_list = []

# Function to Add Guests to the List

def add_guest():
    guest_name = input("Enter the guest's name -> ").strip()
    if guest_name == "":
        print()
        print("Guest name cannot be empty.")
        return
    guest_list.append(guest_name)
    print()
    print(f"{guest_name} has been added to the guest list.")


# Function to Remove Guests from the List

def remove_guest():
    guest_name = input("Enter the guest's name to remove -> ").strip()
    if guest_name in guest_list:
        guest_list.remove(guest_name)
        print()
        print(f"{guest_name} has been removed from the guest list.")
    else:
        print()
        print(f"{guest_name} is not on the list.")

# Function to Print the Guest List

def print_guest_list():
    printable_guests = sorted(guest_list)
    if not printable_guests:
        print()
        print("The guest list is empty.")
    else:
        print()
        print("Current guest list:")
        for guest in printable_guests:
            print(guest)

# Function to Display the Menu and Get User Choice

def menu():
    print("Party Guest List Program")
    print("-" * 24)
    print("Main Menu")
    print("-" * 9)
    print("A. Add a guest")
    print("R. Remove a guest")
    print("P. Print guest list")
    print("Q. Quit the program")
    print()
    choice = input("Enter your choice -> ").upper()
    return choice

# Main Program Loop

while True:
    choice = menu()

    if choice == "A":
        add_guest()
    elif choice == "R":
        remove_guest()
    elif choice == "P":
        print_guest_list()
    elif choice == "Q":
        print()
        print(f"Total number of guests: {len(guest_list)}")
        print()
        print("Goodbye!")
        break
    else:
        print()
        print("Invalid choice. Please choose a valid option (A,R,P or Q).")
    print()